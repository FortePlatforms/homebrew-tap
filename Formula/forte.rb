  version "0.0.5"

  if OS.mac? && Hardware::CPU.arm?
    url "https://github.com/FortePlatforms/homebrew-tap/releases/download/v0.0.5/forte-darwin-arm64"
    sha256 "3563d273119f94ab6cd0ade4ac4e9911b308966d6f0b0677bd44a3b54b0f3b3f"
